#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	int		i;
	char	tab[12];

	i = 0;
	if (n == 0)
		write(fd, "0", 1);
	else if (n == -2147483648)
		write(fd, "-2147483648", 12);
	else
	{
		if (n < 0)
		{
			n = -n;
			write(fd, "-", 1);
		}
		while (n > 0)
		{
			tab[i++] = n % 10 + '0';
			n = n / 10;
		}
		while (i-- > 0)
			write(fd, &tab[i], 1);
	}
}
